export const translations: Record<Lang, Record<TKey, string>> = { en, es };

export type TParams = Record<string, string | number | null | undefined>;

/** Hook-free lookup, used by the engines (which run outside React). */
export function translate(lang: Lang, key: TKey, params?: TParams): string {
  const template = translations[lang][key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    name in params ? String(params[name] ?? '') : match,
  );
}

export type TFn = (key: TKey, params?: TParams) => string;
